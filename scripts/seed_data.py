def main() -> None:
    unverified = [
        row["nama"] for row in KOMPETITOR if row["status_verifikasi"] != "Terverifikasi"
    ]
    if unverified:
        raise SystemExit(
            "Kompetitor berikut belum terverifikasi sehingga tidak boleh masuk dataset: "
            + ", ".join(unverified)
        )

    DATA.mkdir(exist_ok=True)
    frames = {
        "kompetitor.csv": pd.DataFrame(KOMPETITOR, columns=KOMPETITOR_COLUMNS),
        "harga.csv": pd.DataFrame(HARGA, columns=HARGA_COLUMNS),
        "pasar.csv": pd.DataFrame(PASAR, columns=PASAR_COLUMNS),
    }
    for filename, frame in frames.items():
        path = DATA / filename
        frame.to_csv(path, index=False)
        print(f"wrote {path} ({len(frame)} baris)")


if __name__ == "__main__":
    main()
